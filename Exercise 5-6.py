# Umur seseorang
age = 15

# Tentukan tahap kehidupan berdasarkan umur
if age < 2:
    print("Dia masih bayi nih. Lucu banget!")
elif age < 4:
    print("Dia lagi di usia balita. Lagi aktif-aktifnya nih!")
elif age < 13:
    print("Dia masih anak-anak. Waktunya main dan belajar!")
elif age < 20:
    print("Dia remaja nih. Lagi seru-serunya!")
elif age < 65:
    print("Dia udah dewasa. Waktunya kerja keras!")
else:
    print("Dia udah lansia. Waktunya santai dan istirahat!")