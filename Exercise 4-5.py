# Buat list angka dari 1 sampai 1.000.000
numbers = list(range(1, 1000001))

# Cek angka terkecil dan terbesar di dalam list
print(f"Angka terkecil di list: {min(numbers)}")
print(f"Angka terbesar di list: {max(numbers)}")

# Jumlahkan semua angka di dalam list
print(f"Total semua angkanya: {sum(numbers)}")