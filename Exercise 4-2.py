# Daftar hewan yang cocok menjadi hewan peliharaan
animals = ["kucing", "anjing", "kelinci"]

# Tampilkan kalimat untuk setiap hewan
for animal in animals:
    print(f"Anjir, {animal} mah enak sih, asik banget dijadiin peliharaan")

# Kalimat penutup tentang kesamaan hewan-hewan tadi, di luar for loop
print("\nPokoknya hewan mana aja di list ini mah enak banget dipelihara deh")